"""End-to-end check of first- and second-order optimization, from the model to the comparison table.

This covers stages 4-6 of the step 18 verification sequence (see workflows/verify_hessp.sh) in a
single pytest process, on the small tests/tswe.cfg problem:

1. recover the double-vortex offsets (ic-params: ox, oy) from a truth trajectory with L-BFGS-B,
2. recover them again with Newton-CG, using Hessian-vector products,
3. record both runs exactly as optimize_params.run_job does (optimizer_summary, History), write
   them as two optimization roots, and run compare_optimizers.main on them.

Step 3 confirms that the comparison script reports the counts the problem actually performed.
The full shell workflow (truth sweep, optimize_params.sh, compare_optimizers.sh) is the optional
last stage of workflows/verify_hessp.sh, since it needs MPI and takes longer.

These tests need Firedrake and are meant to run in serial.
"""

import time

import numpy as np
import pytest

pytest.importorskip("firedrake")

from dimswe.optimize import ParametricInitialCondition  # noqa: E402

from tests.gradient_helpers import setup_problem  # noqa: E402
from workflows.common import dump_yaml, read_csv, to_builtin  # noqa: E402
from workflows.compare_optimizers import COMPARISON_CSV, main as compare_main  # noqa: E402
from workflows.optimize_params import DEFAULT_OPTIMIZER, History, optimizer_summary  # noqa: E402

pytestmark = pytest.mark.integration

NSTEPS = 3
OBS_STEPS = [1, 3]
PARAM_NAMES = ["ox", "oy"]
# starting point away from the truth of tests/tswe.cfg (ox = oy = 0.1), as in the HVP Taylor tests
START_OFFSET = np.array([0.01, -0.005])
SCALE = np.array([0.1, 0.1])

# the two methods compared, with the optimizer spec entries of the workflow examples
METHOD_SPECS = {
    "L-BFGS-B": {"method": "L-BFGS-B", "maxiter": 40, "ftol": 1.0e-15},
    "Newton-CG": {"method": "Newton-CG", "maxiter": 15, "use_hessp": True, "xtol": 1.0e-8},
}


def run_method(method):
    """Run one ic-params optimization and return everything run_job would record.

    Returns a dict with the optimizer spec, scipy result, ReducedProblem, History, truth and
    initial parameters, optimal parameters, initial and final loss, gtol and wall time.
    """
    setup = setup_problem(NSTEPS, obs_steps=OBS_STEPS)
    ic_map = ParametricInitialCondition(setup.model, setup.parameters, PARAM_NAMES)
    truth = ic_map.get_initial_values(setup.parameters)
    initial = truth + START_OFFSET
    problem = setup.optimizer.reduced_problem(initial, opt_type="ic-params", coeffs0=setup.coeff, ic_map=ic_map,
                                              scaling_factors=SCALE)
    # relative gtol, as with the workflow's default optimizer.tolerance: relative
    gtol = 1.0e-8 * float(np.max(np.abs(problem.jac(problem.z0))))
    spec = {**DEFAULT_OPTIMIZER, "gtol": gtol, **METHOD_SPECS[method]}
    history = History(PARAM_NAMES, problem=problem)
    start = time.perf_counter()
    x_opt, result = setup.optimizer.optimize(
        None, method=spec["method"], gtol=gtol, ftol=spec["ftol"], maxiter=spec["maxiter"], callback=history,
        return_result=True, problem=problem, use_hessp=spec["use_hessp"], use_bounds=spec["use_bounds"],
        xtol=spec["xtol"])
    seconds = time.perf_counter() - start
    return {
        "spec": spec, "result": result, "problem": problem, "history": history, "truth": truth,
        "initial": initial, "x_opt": np.asarray(x_opt), "initial_loss": history.rows[0]["loss"],
        "final_loss": float(result.fun), "gtol": gtol, "seconds": seconds,
    }


@pytest.fixture(scope="module")
def runs():
    """Both optimizations, run once for all tests in this module."""
    return {method: run_method(method) for method in METHOD_SPECS}


@pytest.mark.parametrize("method", list(METHOD_SPECS))
def test_both_methods_recover_the_truth(runs, method):
    run = runs[method]
    print(method, run["result"].message, run["x_opt"], run["final_loss"] / run["initial_loss"])
    # the truth is generated by the same model, so the loss can be driven far down
    assert run["final_loss"] <= 1.0e-4 * run["initial_loss"]
    initial_error = np.max(np.abs(run["initial"] - run["truth"]))
    assert np.max(np.abs(run["x_opt"] - run["truth"])) <= 0.05 * initial_error


def test_only_the_second_order_method_uses_hvps(runs):
    first, second = runs["L-BFGS-B"], runs["Newton-CG"]
    assert first["problem"].nhvp == 0 and first["result"].hessp_used is False
    assert second["problem"].nhvp > 0 and second["result"].hessp_used is True
    for run in (first, second):
        problem, result = run["problem"], run["result"]
        # optimize() reports the problem's own counters
        assert (result.problem_nfev, result.problem_njev, result.problem_nhvp) == (problem.nfev, problem.njev, problem.nhvp)
        assert problem.nfev > 0 and problem.njev > 0


@pytest.mark.parametrize("method", list(METHOD_SPECS))
def test_history_counters_are_cumulative(runs, method):
    run = runs[method]
    rows = run["history"].rows
    assert rows[0]["iteration"] == 0 and rows[0]["nhvp"] == 0
    for counter in ("nfev", "njev", "nhvp"):
        values = [row[counter] for row in rows]
        assert values == sorted(values), counter
        # evaluations after the last callback (scipy's final checks) are not in the history
        assert values[-1] <= getattr(run["problem"], counter)
    if method == "Newton-CG":
        assert rows[-1]["nhvp"] > 0


def write_root(root, run):
    """Write one job of an optimization root, with result.yaml in run_job's layout."""
    result = {
        "job_name": "tswe__trajectory-1-3", "target": "ic-params", "loss_label": "trajectory-1-3",
        "truth_runs": ["tswe"],
        "optimizer": optimizer_summary(run["spec"], run["result"], run["problem"], run["gtol"]),
        "initial_loss": run["initial_loss"], "final_loss": run["final_loss"], "optimize_seconds": run["seconds"],
        "parameters": {
            f"initial-conditions.{name}": {
                "initial": float(initial), "optimal": float(optimal), "true": float(true),
                "rel_error": abs(float(optimal) - float(true)) / abs(float(true)),
            }
            for name, initial, optimal, true in zip(PARAM_NAMES, run["initial"], run["x_opt"], run["truth"])
        },
    }
    dump_yaml(to_builtin(result), root / result["job_name"] / "result.yaml")


def test_comparison_script_reports_the_recorded_counts(runs, tmp_path, capsys):
    roots = {"L-BFGS-B": tmp_path / "tswe-params", "Newton-CG": tmp_path / "tswe-params-newton-cg"}
    for method, root in roots.items():
        write_root(root, runs[method])
    csv_path, yaml_path = compare_main([str(root) for root in roots.values()])
    out = capsys.readouterr().out
    print(out)
    assert "Optimizer comparison: 2 job(s), 1 problem(s)" in out

    rows = {row["method"]: row for row in read_csv(csv_path)}
    assert csv_path.name == COMPARISON_CSV and set(rows) == set(METHOD_SPECS)
    for method, row in rows.items():
        run = runs[method]
        problem = run["problem"]
        assert (row["nfev"], row["njev"], row["nhvp"]) == (problem.nfev, problem.njev, problem.nhvp)
        assert row["nit"] == int(run["result"].nit)
        assert row["final_loss"] == pytest.approx(run["final_loss"], rel=1e-12)
        assert row["hessp_used"] == str(method == "Newton-CG")
        assert row["nmethods"] == 2
    ratios = sorted(row["final_loss_vs_best"] for row in rows.values())
    assert ratios[0] == 1.0 and ratios[1] >= 1.0
    assert yaml_path.exists()
